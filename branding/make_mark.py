#!/usr/bin/env python3
"""Generates the Raheel Optics mark (glasses + eye) as Android vector drawables and an SVG source."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = f"{ROOT}/branding/android-res"

LENS_L = "M4,16 C4,13 6,12 9,12 L35,12 C38,12 40,14 40,17 C40,31 33,42 22,42 C11,42 4,31 4,16 Z"
LENS_R = "M96,16 C96,13 94,12 91,12 L65,12 C62,12 60,14 60,17 C60,31 67,42 78,42 C89,42 96,31 96,16 Z"
TEMPLES = "M4,15 L1,14 M96,15 L99,14"
BROW = "M37,8.5 C44,0.5 59,0 67,7.5 C58,3.8 46,4.2 37,8.5 Z"
SWEEP = "M35,40 C42,46.8 57,47.2 65,40.5 C56,44.2 44,44 35,40 Z"
EYE = "M32,26 C39,13.5 61,13.5 68,26 C61,38.5 39,38.5 32,26 Z"
# A counter-clockwise box around the clockwise EYE outline: with non-zero winding this clip is everything except the eye.
OUTSIDE_EYE = "M-10,-10 L-10,60 L110,60 L110,-10 Z " + EYE

def circle(cx, cy, r):
    return f"M{cx - r:g},{cy} a{r:g},{r:g} 0 1,0 {2 * r:g},0 a{r:g},{r:g} 0 1,0 {-2 * r:g},0"

LIGHT = dict(frame="#0B2F68", sclera="#FFFFFF", iris="#1A7FE0", pupil="#04214F", green="#079E6B", highlight="#FFFFFF")
DARK = dict(frame="#D6E6FA", sclera="#F4F8FD", iris="#2F8CEB", pupil="#04214F", green="#2CC48C", highlight="#FFFFFF")

def stroke(d, color, width, cap=False):
    end = 'android:strokeLineCap="round"' if cap else 'android:strokeLineJoin="round"'
    return f'<path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{width}" {end} />'

def fill(d, color):
    return f'<path android:pathData="{d}" android:fillColor="{color}" />'

def colour_paths(c):
    return [
        stroke(LENS_L, c["frame"], 4.6), stroke(LENS_R, c["frame"], 4.6), stroke(TEMPLES, c["frame"], 4.6, cap=True),
        fill(BROW, c["green"]), fill(SWEEP, c["green"]),
        f'<path android:pathData="{EYE}" android:fillColor="{c["sclera"]}" android:strokeColor="{c["frame"]}" android:strokeWidth="3.6" android:strokeLineJoin="round" />',
        fill(circle(50, 26, 7.8), c["iris"]), fill(circle(50, 26, 4.2), c["pupil"]), fill(circle(52.9, 23.1, 1.8), c["highlight"]),
    ]

def mono_paths(color="#FFFFFF"):
    # One colour, no solid fills: the launcher tints it, so the lenses are clipped where the eye sits.
    return [
        f'<group><clip-path android:pathData="{OUTSIDE_EYE}" />',
        stroke(LENS_L, color, 4.6), stroke(LENS_R, color, 4.6), stroke(TEMPLES, color, 4.6, cap=True),
        "</group>",
        fill(BROW, color), fill(SWEEP, color), stroke(EYE, color, 3.6),
        stroke(circle(50, 26, 7), color, 3), fill(circle(50, 26, 3.2), color),
    ]

def vector(paths, width, height, vw, vh, transform=None, comment=""):
    body = "\n".join("        " + p for p in paths) if transform else "\n".join("    " + p for p in paths)
    if transform:
        body = f'    <group android:translateX="{transform[0]}" android:translateY="{transform[1]}" android:scaleX="{transform[2]}" android:scaleY="{transform[2]}">\n{body}\n    </group>'
    note = f"<!-- {comment} -->\n" if comment else ""
    return (f'{note}<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{width}dp" android:height="{height}dp"\n'
            f'    android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n{body}\n</vector>\n')

# The 100x47 mark scaled to 70 units wide and centred in the 108 launcher canvas (inside the 72-unit visible area).
LAUNCHER = (19, 37.5, 0.7)
# The Android 12+ splash icon is scaled like a launcher icon and masked to a circle, so it uses the same canvas, smaller.
SPLASH = (23, 39.4, 0.62)
SOURCE = "Generated by branding/make_mark.py; edit there and rerun."

files = {
    f"{RES}/drawable/ic_brand_mark_light.xml": vector(colour_paths(LIGHT), 100, 50, 100, 50, comment="Brand mark for light backgrounds. " + SOURCE),
    f"{RES}/drawable/ic_brand_mark_dark.xml": vector(colour_paths(DARK), 100, 50, 100, 50, comment="Brand mark for dark backgrounds. " + SOURCE),
    f"{RES}/drawable/ic_launcher_foreground.xml": vector(colour_paths(LIGHT), 108, 108, 108, 108, LAUNCHER, comment="Launcher icon foreground. " + SOURCE),
    f"{RES}/drawable/splash_mark.xml": vector(colour_paths(LIGHT), 108, 108, 108, 108, SPLASH, comment="Android 12+ splash icon. " + SOURCE),
    f"{RES}/drawable-night/splash_mark.xml": vector(colour_paths(DARK), 108, 108, 108, 108, SPLASH, comment="Android 12+ splash icon, dark. " + SOURCE),
    f"{RES}/drawable/ic_launcher_monochrome.xml": vector(mono_paths(), 108, 108, 108, 108, LAUNCHER, comment="Themed (tinted) launcher icon. " + SOURCE),
}

def svg(c):
    def p(d, **a):
        return "  <path d=\"%s\" %s/>" % (d, " ".join(f'{k.replace("_", "-")}="{v}"' for k, v in a.items()))
    rows = [
        p(LENS_L, fill="none", stroke=c["frame"], stroke_width=4.6, stroke_linejoin="round"),
        p(LENS_R, fill="none", stroke=c["frame"], stroke_width=4.6, stroke_linejoin="round"),
        p(TEMPLES, fill="none", stroke=c["frame"], stroke_width=4.6, stroke_linecap="round"),
        p(BROW, fill=c["green"]), p(SWEEP, fill=c["green"]),
        p(EYE, fill=c["sclera"], stroke=c["frame"], stroke_width=3.6, stroke_linejoin="round"),
        p(circle(50, 26, 7.8), fill=c["iris"]), p(circle(50, 26, 4.2), fill=c["pupil"]), p(circle(52.9, 23.1, 1.8), fill=c["highlight"]),
    ]
    return '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="200" viewBox="0 0 100 50">\n' + "\n".join(rows) + "\n</svg>\n"

files[f"{ROOT}/branding/raheel-optics-mark.svg"] = svg(LIGHT)
files[f"{ROOT}/branding/raheel-optics-mark-dark.svg"] = svg(DARK)

for path, text in files.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)
    print("wrote", path.replace(ROOT + "/", ""))
